// Writes src/ui/lucide-glyphs.ts: the Lucide font glyph of each app icon.
// Run `bun run scripts/lucide-glyphs.ts` in apps/mobile after a change to src/ui/icon-names.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { ICONS } from "../src/ui/icon-names";

const require = createRequire(import.meta.url);
const codepointsPath = join(
  dirname(require.resolve("lucide-static/package.json")),
  "font/codepoints.json",
);
const codepoints: Record<string, number> = JSON.parse(readFileSync(codepointsPath, "utf8"));
const names = [...new Set(Object.values(ICONS))].sort();
const lines = names.map((name) => {
  const codepoint = codepoints[name];
  if (codepoint === undefined) throw new Error(`The Lucide font has no glyph named ${name}.`);
  return `  "${name}": "\\u{${codepoint.toString(16)}}",`;
});
writeFileSync(
  join(import.meta.dir, "../src/ui/lucide-glyphs.ts"),
  [
    "// Generated by scripts/lucide-glyphs.ts from the lucide-static font. Do not edit.",
    'import type { LucideName } from "./icon-names";',
    "",
    "/** The Lucide font glyph of each Lucide icon that an app icon uses. */",
    "export const LUCIDE_GLYPHS = {",
    ...lines,
    "} as const satisfies Record<LucideName, string>;",
    "",
  ].join("\n"),
);
console.info(`Wrote ${names.length} glyphs.`);
