// The theme of the scenes: the desktop tokens of @openducktor/theme, applied to the replica root
// only, so a host page keeps its own tokens. The dark tokens follow `data-theme="dark"` on the
// page root or on the scene root. Each theme also gets `--brand`, the sRGB value of its
// `--primary`, so the scenes need no color from the host page.
import { readThemeBlocks } from "@openducktor/theme/blocks";
import { colorResolver, readDeclarations, toHex } from "@openducktor/theme/colors";

/** The file that `bun run build:theme` writes, and that a test compares with its source. */
export const THEME_FILE = new URL("../styles/theme.css", import.meta.url);

/** The declarations of a theme block with `--brand` at the end. */
function withBrand(block: string): string {
  const brand = toHex(colorResolver(readDeclarations(block))("primary"));
  return `${block}
  /* --primary in sRGB, for a mix in sRGB and for the glow tweens of the scenes. */
  --brand: ${brand};
`;
}

/** The stylesheet of the scene theme for the token file `source`. */
export function sceneTheme(source: string): string {
  const { light, dark } = readThemeBlocks(source);
  return [
    "/* Generated by scripts/build-theme.ts from @openducktor/theme/tokens.css. Do not edit. */",
    "@layer product {",
    `  :where(.stage) .replica {${withBrand(light)}}`,
    `  :is(:root, .scene)[data-theme="dark"] :where(.stage) .replica {${withBrand(dark)}}`,
    "}",
    "",
  ].join("\n");
}
